/// 作息时间表。
///
/// 注意：各学院/各校区上课时间并不统一，这里的默认值只是常见的一套，
/// 可以在「更多 → 作息时间」里改。课表本身不显示时刻（避免显示错的），
/// 只有桌面小组件的倒计时用它。
class PeriodTimes {
  PeriodTimes._();

  /// (开始, 结束)
  static const List<(String, String)> defaults = [
    ('08:30', '09:15'),
    ('09:20', '10:05'),
    ('10:25', '11:10'),
    ('11:15', '12:00'),
    ('14:30', '15:15'),
    ('15:20', '16:05'),
    ('16:25', '17:10'),
    ('17:15', '18:00'),
    ('19:00', '19:45'),
    ('19:50', '20:35'),
    ('20:40', '21:25'),
    ('21:30', '22:15'),
  ];

  static int get count => defaults.length;

  static const weekLabels = ['一', '二', '三', '四', '五', '六', '日'];
  static const weekFull = ['周一', '周二', '周三', '周四', '周五', '周六', '周日'];
}
